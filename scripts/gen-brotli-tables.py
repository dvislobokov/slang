#!/usr/bin/env python3
"""Generates runtime/src/std_brotli_tables.h from the system libbrotlicommon
(Debian/Ubuntu package libbrotli1): the RFC 7932 static dictionary
(Appendix A, 122784 bytes, stored zstd-compressed and expanded by the
runtime's own zstd decoder on first use), the 121 word transforms
(Appendix B) and the literal context lookup tables (section 7.1).
Requires the `zstd` CLI. Run: python3 scripts/gen-brotli-tables.py"""
import ctypes, hashlib, os, subprocess

lib = ctypes.CDLL("libbrotlicommon.so.1")

class Dictionary(ctypes.Structure):
    _fields_ = [("size_bits_by_length", ctypes.c_uint8 * 32), ("offsets_by_length", ctypes.c_uint32 * 32),
                ("data_size", ctypes.c_size_t), ("data", ctypes.POINTER(ctypes.c_uint8))]

class Transforms(ctypes.Structure):
    _fields_ = [("prefix_suffix_size", ctypes.c_uint16), ("prefix_suffix", ctypes.POINTER(ctypes.c_uint8)),
                ("prefix_suffix_map", ctypes.POINTER(ctypes.c_uint16)), ("num_transforms", ctypes.c_uint32),
                ("transforms", ctypes.POINTER(ctypes.c_uint8)), ("params", ctypes.POINTER(ctypes.c_uint8)),
                ("cutOffTransforms", ctypes.c_int16 * 10)]

lib.BrotliGetDictionary.restype = ctypes.POINTER(Dictionary)
lib.BrotliGetTransforms.restype = ctypes.POINTER(Transforms)
d = lib.BrotliGetDictionary().contents
t = lib.BrotliGetTransforms().contents
data = bytes(d.data[:d.data_size])
assert len(data) == 122784
z = subprocess.run(["zstd", "-19", "-q", "-c"], input=data, stdout=subprocess.PIPE, check=True).stdout
ps = bytes(t.prefix_suffix[:t.prefix_suffix_size])
assert t.num_transforms == 121

def strat(off):
    n = ps[off]
    return ps[off + 1:off + 1 + n]

rows = []
for i in range(121):
    p, typ, s = t.transforms[3 * i], t.transforms[3 * i + 1], t.transforms[3 * i + 2]
    rows.append((strat(t.prefix_suffix_map[p]), typ, strat(t.prefix_suffix_map[s])))
lut = ctypes.cast(ctypes.addressof(ctypes.c_uint8.in_dll(lib, "_kBrotliContextLookupTable")), ctypes.POINTER(ctypes.c_uint8))
ctx = bytes(lut[:2048])

def cstr(b):
    return '"' + "".join("\\x%02x" % c for c in b) + '"'

out = []
out.append("/* std_brotli_tables.h - generated by scripts/gen-brotli-tables.py from libbrotlicommon: do not edit.")
out.append(" * RFC 7932 static dictionary (zstd-compressed, sha256 %s)," % hashlib.sha256(data).hexdigest())
out.append(" * word transforms (Appendix B) and literal context lookup tables (7.1). */")
out.append("static const uint8_t brotli_dict_size_bits[32] = {%s};" % ", ".join(str(x) for x in d.size_bits_by_length))
out.append("static const uint32_t brotli_dict_offsets[32] = {%s};" % ", ".join(str(x) for x in d.offsets_by_length))
out.append("#define BROTLI_DICT_SIZE %d" % len(data))
out.append("static const uint8_t brotli_dict_zstd[%d] = {" % len(z))
for i in range(0, len(z), 24):
    out.append("    " + ", ".join(str(c) for c in z[i:i + 24]) + ",")
out.append("};")
out.append("typedef struct { const char *prefix; uint8_t plen; uint8_t type; const char *suffix; uint8_t slen; } brotli_transform;")
out.append("static const brotli_transform brotli_transforms[121] = {")
for p, typ, s in rows:
    out.append("    {%s, %d, %d, %s, %d}," % (cstr(p), len(p), typ, cstr(s), len(s)))
out.append("};")
out.append("/* context lookup: mode m uses [m * 512 + p1] | [m * 512 + 256 + p2] (LSB6, MSB6, UTF8, signed) */")
out.append("static const uint8_t brotli_context_lut[2048] = {")
for i in range(0, 2048, 32):
    out.append("    " + ", ".join(str(c) for c in ctx[i:i + 32]) + ",")
out.append("};")
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "runtime", "src", "std_brotli_tables.h")
open(path, "w").write("\n".join(out) + "\n")
print("wrote", os.path.normpath(path), len(z), "compressed dictionary bytes")
