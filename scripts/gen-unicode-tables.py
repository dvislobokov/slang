#!/usr/bin/env python3
"""Generates runtime/src/std_unicode_tables.c (the range tables behind
std.unicode) from Go's unicode/tables.go, which is itself generated from
the Unicode Character Database.

Usage: scripts/gen-unicode-tables.py [path/to/go/src/unicode/tables.go]
(default: $(go env GOROOT)/src/unicode/tables.go or /usr/local/go/...).
"""
import os
import re
import subprocess
import sys

TABLES = ["C", "Cc", "L", "Lu", "Ll", "Lt", "M", "N", "Nd", "P", "S", "Zs", "White_Space"]


def goroot_tables():
    try:
        root = subprocess.check_output(["go", "env", "GOROOT"], text=True).strip()
        p = os.path.join(root, "src/unicode/tables.go")
        if os.path.exists(p):
            return p
    except Exception:
        pass
    return "/usr/local/go/src/unicode/tables.go"


def main():
    src_path = sys.argv[1] if len(sys.argv) > 1 else goroot_tables()
    src = open(src_path, encoding="utf-8").read()
    version = re.search(r'const Version = "([^"]+)"', src).group(1)
    out = []
    out.append("/* std_unicode_tables.c - GENERATED by scripts/gen-unicode-tables.py from\n"
               " * Go's unicode/tables.go (Unicode %s). DO NOT EDIT.\n"
               " * Range tables: {lo, hi, stride} triples sorted by lo; case ranges:\n"
               " * {lo, hi, delta_upper, delta_lower, delta_title}, where a delta of\n"
               " * 0x110000 means alternating upper/lower pairs. */\n" % version)
    out.append('#include <stdint.h>\n')
    out.append('const char zell__unicode_version[] = "%s";\n' % version)
    for name in TABLES:
        m = re.search(r"\nvar _%s = &RangeTable\{(.*?)\n\}\n" % re.escape(name), src, re.S)
        if not m:
            sys.exit("table %s not found" % name)
        body = m.group(1)
        triples = re.findall(r"\{(0x[0-9a-fA-F]+), (0x[0-9a-fA-F]+), (\d+)\}", body)
        cname = name.lower()
        out.append("\nconst uint32_t zell__unicode_%s[][3] = {" % cname)
        line = []
        for lo, hi, st in triples:
            line.append("{%s, %s, %s}" % (lo, hi, st))
            if len(line) == 4:
                out.append("    " + ", ".join(line) + ",")
                line = []
        if line:
            out.append("    " + ", ".join(line) + ",")
        out.append("};")
        out.append("const int zell__unicode_%s_len = %d;" % (cname, len(triples)))
    m = re.search(r"\nvar _CaseRanges = \[\]CaseRange\{(.*?)\n\}\n", src, re.S)
    rows = re.findall(r"\{(0x[0-9A-Fa-f]+), (0x[0-9A-Fa-f]+), d\{([^}]*)\}\}", m.group(1))
    out.append("\nconst int32_t zell__unicode_case[][5] = {")
    for lo, hi, d in rows:
        ds = [x.strip().replace("UpperLower", "0x110000") for x in d.split(",")]
        out.append("    {%s, %s, %s}," % (lo, hi, ", ".join(ds)))
    out.append("};")
    out.append("const int zell__unicode_case_len = %d;" % len(rows))
    here = os.path.dirname(os.path.abspath(__file__))
    dst = os.path.join(here, "..", "runtime", "src", "std_unicode_tables.c")
    with open(dst, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", os.path.normpath(dst))


if __name__ == "__main__":
    main()
