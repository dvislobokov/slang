//! `slang.lock`: a deterministic YAML description of every package in the
//! graph (sorted packages, sorted dependency lists, alphabetical keys).
//!
//! Every package of the graph has an entry: `name`, `version`, `source`
//! ([`Source::lock_id`](super::graph::Source::lock_id)), `dependencies`
//! (package names) and `checksum`. Path packages: `source: path:<dir>`,
//! `checksum: sha256:<hex>` over the sources ([`checksum`]). Module
//! packages add `module: <path>`, have `version: v1.2.3` (the selected
//! tag or a pseudo-version), `source: module` (MVS over tags) or
//! `git+<url>?tag=|branch=|rev=<ref>#<commit>` (a git pin), and
//! `checksum: h1:...` over the module tree ([`super::sum`]), checked on
//! every download.

use super::graph::Project;
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::path::Path;

/// Version of the lock-file format.
pub const LOCK_VERSION: u32 = 1;

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct LockFile {
    pub packages: Vec<LockedPackage>,
    pub version: u32,
}

/// Keys are alphabetical so the YAML is sorted.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct LockedPackage {
    /// `sha256:<hex>` over the package's sorted source files.
    pub checksum: String,
    /// Names of the direct dependencies (and dev-dependencies), sorted.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub dependencies: Vec<String>,
    /// Module path of a module package.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub module: Option<String>,
    pub name: String,
    pub source: String,
    pub version: String,
}

const HEADER: &str = "# slang.lock: generated by `slang`, do not edit by hand.\n";

impl LockFile {
    /// The lock file describing `project`'s current state.
    pub fn of(project: &Project) -> Result<LockFile, String> {
        let mut packages = Vec::new();
        for p in &project.packages {
            let mut deps: Vec<String> = p.deps.iter().chain(&p.dev_deps).map(|&d| project.packages[d].name.clone()).collect();
            deps.sort();
            deps.dedup();
            let (sum, module, version) = match &p.source {
                super::graph::Source::Module { path, version, h1, .. } => (h1.clone(), Some(path.clone()), version.clone()),
                super::graph::Source::Path(_) => (checksum(&p.dir, &p.source_files()?)?, None, p.version.clone()),
            };
            packages.push(LockedPackage { checksum: sum, dependencies: deps, module, name: p.name.clone(), source: p.source.lock_id(), version });
        }
        packages.sort_by(|a, b| (&a.name, &a.version, &a.source).cmp(&(&b.name, &b.version, &b.source)));
        Ok(LockFile { packages, version: LOCK_VERSION })
    }

    pub fn to_yaml(&self) -> String {
        format!("{HEADER}{}", serde_yaml::to_string(self).expect("lock file serialises"))
    }

    pub fn parse(text: &str) -> Result<LockFile, String> {
        serde_yaml::from_str(text).map_err(|e| e.to_string())
    }
}

/// `sha256:<hex>` over `files` (relative path, length and bytes of each,
/// sorted by relative path) of the package in `dir`.
pub fn checksum(dir: &Path, files: &[std::path::PathBuf]) -> Result<String, String> {
    let mut rel: Vec<(String, &std::path::PathBuf)> = files
        .iter()
        .map(|f| {
            let r = f.strip_prefix(dir).unwrap_or(f);
            (r.components().map(|c| c.as_os_str().to_string_lossy().to_string()).collect::<Vec<_>>().join("/"), f)
        })
        .collect();
    rel.sort();
    let mut h = Sha256::new();
    for (r, f) in rel {
        let bytes = std::fs::read(f).map_err(|e| format!("cannot read {}: {e}", f.display()))?;
        h.update(r.as_bytes());
        h.update([0]);
        h.update((bytes.len() as u64).to_le_bytes());
        h.update(&bytes);
    }
    Ok(format!("sha256:{}", hex(&h.finalize())))
}

pub fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

/// What [`sync`] did.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LockStatus {
    Unchanged,
    Written,
}

/// Brings `slang.lock` up to date: rewrites it when the graph, versions or
/// sources changed. With `locked`, a needed change is an error instead.
pub fn sync(project: &Project, locked: bool) -> Result<LockStatus, String> {
    let want = LockFile::of(project)?.to_yaml();
    let path = project.lock_path();
    let have = std::fs::read_to_string(&path).ok();
    if have.as_deref() == Some(want.as_str()) {
        return Ok(LockStatus::Unchanged);
    }
    if locked {
        let why = match &have {
            None => "it does not exist".to_string(),
            Some(old) => match LockFile::parse(old) {
                Ok(old) => describe_change(&old, &LockFile::parse(&want).unwrap()),
                Err(_) => "it is malformed".to_string(),
            },
        };
        return Err(format!("{} needs to be updated ({why}), but --locked was given", path.display()));
    }
    std::fs::write(&path, want).map_err(|e| format!("cannot write {}: {e}", path.display()))?;
    Ok(LockStatus::Written)
}

fn describe_change(old: &LockFile, new: &LockFile) -> String {
    for p in &new.packages {
        match old.packages.iter().find(|o| o.name == p.name) {
            None => return format!("package `{}` was added", p.name),
            Some(o) if o != p => {
                let what = if o.version != p.version {
                    "version"
                } else if o.dependencies != p.dependencies {
                    "dependencies"
                } else if o.source != p.source {
                    "source"
                } else {
                    "sources (checksum)"
                };
                return format!("{what} of `{}` changed", p.name);
            }
            _ => {}
        }
    }
    for o in &old.packages {
        if !new.packages.iter().any(|p| p.name == o.name) {
            return format!("package `{}` was removed", o.name);
        }
    }
    "format changed".into()
}
