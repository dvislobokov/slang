//! `zell init --agents claude,codex,...`: configuration that gives AI
//! coding agents Zell language intelligence (see `agents/README.md`):
//! the agent guide (the `zell` and `zell-packages` skills of
//! `agents/claude-code`) as the agent's instruction file, and the
//! `zell-mcp` server in the agent's MCP configuration.
//!
//! Existing files are merged, never clobbered: Markdown instruction files
//! get a marked section (replaced on the next run), JSON and TOML
//! configurations get the `zell` server entry. A file that cannot be
//! parsed (JSON with comments, say) is left alone with a note saying what
//! to add by hand.

use std::path::{Path, PathBuf};

/// The `zell` skill (its frontmatter is dropped in instruction files).
pub const ZELL_SKILL: &str = include_str!("../../../agents/claude-code/skills/zell/SKILL.md");
/// The `zell-packages` skill.
pub const PACKAGES_SKILL: &str = include_str!("../../../agents/claude-code/skills/zell-packages/SKILL.md");

/// The marketplace that serves the Claude Code plugin.
pub const MARKETPLACE_REPO: &str = "zell-lang/zell";

const BEGIN: &str = "<!-- zell:begin (generated by `zell init --agents`; edits between these markers are replaced) -->";
const END: &str = "<!-- zell:end -->";

/// An agent `zell init --agents` knows.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Agent {
    /// Claude Code: the plugin (LSP, MCP, hook, skills) via `.claude/settings.json`.
    Claude,
    /// Claude Code without the plugin: `.claude/skills/` + `.mcp.json`.
    ClaudeSkills,
    Codex,
    Gemini,
    Cursor,
    Windsurf,
    Cline,
    Aider,
    Zed,
    /// GitHub Copilot in VS Code (agent mode).
    Copilot,
}

impl Agent {
    pub const ALL: &[Agent] = &[Agent::Claude, Agent::Codex, Agent::Gemini, Agent::Cursor, Agent::Windsurf, Agent::Cline, Agent::Aider, Agent::Zed, Agent::Copilot];

    pub fn name(self) -> &'static str {
        match self {
            Agent::Claude => "claude",
            Agent::ClaudeSkills => "claude-skills",
            Agent::Codex => "codex",
            Agent::Gemini => "gemini",
            Agent::Cursor => "cursor",
            Agent::Windsurf => "windsurf",
            Agent::Cline => "cline",
            Agent::Aider => "aider",
            Agent::Zed => "zed",
            Agent::Copilot => "copilot",
        }
    }

    fn parse(s: &str) -> Option<Agent> {
        let all = [Agent::ClaudeSkills].iter().chain(Agent::ALL);
        all.copied().find(|a| a.name() == s).or(match s {
            "claude-code" => Some(Agent::Claude),
            "gemini-cli" => Some(Agent::Gemini),
            "vscode" => Some(Agent::Copilot),
            _ => None,
        })
    }
}

/// Parses `claude,codex` (or `all`).
pub fn parse_list(list: &str) -> Result<Vec<Agent>, String> {
    let mut out: Vec<Agent> = Vec::new();
    for part in list.split(',').map(str::trim).filter(|p| !p.is_empty()) {
        let add: Vec<Agent> = if part == "all" {
            Agent::ALL.to_vec()
        } else {
            vec![Agent::parse(part).ok_or_else(|| {
                let names: Vec<&str> = Agent::ALL.iter().map(|a| a.name()).collect();
                format!("unknown agent `{part}` (known: {}, claude-skills, all)", names.join(", "))
            })?]
        };
        for a in add {
            if !out.contains(&a) {
                out.push(a);
            }
        }
    }
    if out.is_empty() {
        return Err("--agents needs a list such as claude,codex (or all)".into());
    }
    Ok(out)
}

/// A skill's text without its YAML frontmatter.
pub fn skill_body(skill: &str) -> &str {
    skill.strip_prefix("---\n").and_then(|rest| rest.find("\n---\n").map(|i| &rest[i + 5..])).unwrap_or(skill).trim_start_matches('\n')
}

/// Markdown with every heading one level deeper (outside code fences).
fn demote(md: &str) -> String {
    let mut fence = false;
    let mut out = String::with_capacity(md.len() + 64);
    for line in md.lines() {
        if line.starts_with("```") {
            fence = !fence;
        }
        if !fence && line.starts_with('#') {
            out.push('#');
        }
        out.push_str(line);
        out.push('\n');
    }
    out
}

/// The agent guide: both skills, as a section of an instruction file
/// (`AGENTS.md`, `GEMINI.md`, rules), between the zell markers.
pub fn guide_section() -> String {
    format!("{BEGIN}\n{}\n{}{END}\n", demote(skill_body(ZELL_SKILL)).trim_end(), demote(&format!("\n{}", skill_body(PACKAGES_SKILL))))
}

/// The guide as a standalone instruction file (a title, then the section).
pub fn guide_file() -> String {
    format!("# Zell\n\n{}", guide_section())
}

/// A Cursor rule (`.cursor/rules/zell.mdc`).
pub fn cursor_rule() -> String {
    format!("---\ndescription: Zell language guide (syntax, errors, async, memory, tests, CLI, packages)\nglobs: \"**/*.zl\"\nalwaysApply: false\n---\n\n{}", guide_file())
}

/// A Windsurf rule (`.windsurf/rules/zell.md`).
pub fn windsurf_rule() -> String {
    format!("---\ntrigger: glob\nglobs: \"**/*.zl\"\n---\n\n{}", guide_file())
}

/// What happened to one file.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Outcome {
    Created,
    Updated,
    Unchanged,
    /// Left alone; the note says what to do by hand.
    Skipped(String),
}

/// The result of [`write`].
#[derive(Debug, Default)]
pub struct Report {
    pub files: Vec<(PathBuf, Outcome)>,
    /// Steps outside the project (user-level configuration).
    pub notes: Vec<String>,
}

fn put(report: &mut Report, path: PathBuf, old: Option<&str>, new: &str) -> Result<(), String> {
    if old == Some(new) {
        report.files.push((path, Outcome::Unchanged));
        return Ok(());
    }
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir).map_err(|e| format!("cannot create {}: {e}", dir.display()))?;
    }
    std::fs::write(&path, new).map_err(|e| format!("cannot write {}: {e}", path.display()))?;
    report.files.push((path, if old.is_some() { Outcome::Updated } else { Outcome::Created }));
    Ok(())
}

/// Writes (or refreshes) the zell section of a Markdown instruction file.
fn markdown_section(report: &mut Report, path: PathBuf) -> Result<(), String> {
    let old = std::fs::read_to_string(&path).ok();
    let section = guide_section();
    let new = match &old {
        None => guide_file(),
        Some(text) => match (text.find(BEGIN), text.find(END)) {
            (Some(b), Some(e)) if e > b => format!("{}{section}{}", &text[..b], text[e + END.len()..].trim_start_matches('\n')),
            _ => format!("{}{}\n{section}", text, if text.ends_with('\n') || text.is_empty() { "" } else { "\n" }),
        },
    };
    put(report, path, old.as_deref(), &new)
}

/// A whole file owned by zell (a rule or skill): rewritten.
fn owned_file(report: &mut Report, path: PathBuf, text: &str) -> Result<(), String> {
    let old = std::fs::read_to_string(&path).ok();
    put(report, path, old.as_deref(), text)
}

/// Sets `keys` (a path of object keys) to `value` in a JSON file.
fn json_entry(report: &mut Report, path: PathBuf, keys: &[&str], value: serde_json::Value) -> Result<(), String> {
    let old = std::fs::read_to_string(&path).ok();
    let mut doc: serde_json::Value = match &old {
        None => serde_json::json!({}),
        Some(t) if t.trim().is_empty() => serde_json::json!({}),
        Some(t) => match serde_json::from_str(t) {
            Ok(v @ serde_json::Value::Object(_)) => v,
            _ => {
                let snippet = keys.iter().rev().fold(value, |v, k| serde_json::json!({ *k: v }));
                let note = format!("not plain JSON; add by hand: {}", serde_json::to_string(&snippet).unwrap_or_default());
                report.files.push((path, Outcome::Skipped(note)));
                return Ok(());
            }
        },
    };
    let mut at = &mut doc;
    for k in &keys[..keys.len() - 1] {
        let obj = at.as_object_mut().expect("objects all the way down");
        let next = obj.entry(k.to_string()).or_insert_with(|| serde_json::json!({}));
        if !next.is_object() {
            *next = serde_json::json!({});
        }
        at = next;
    }
    at.as_object_mut().expect("object").insert(keys[keys.len() - 1].to_string(), value);
    let new = serde_json::to_string_pretty(&doc).map_err(|e| e.to_string())? + "\n";
    put(report, path, old.as_deref(), &new)
}

/// `[mcp_servers.zell]` in a Codex `config.toml`.
fn codex_toml(report: &mut Report, path: PathBuf) -> Result<(), String> {
    let old = std::fs::read_to_string(&path).ok();
    let mut doc = match old.as_deref().unwrap_or("").parse::<toml_edit::DocumentMut>() {
        Ok(d) => d,
        Err(_) => {
            report.files.push((path, Outcome::Skipped("not valid TOML; add [mcp_servers.zell] with command = \"zell-mcp\" by hand".into())));
            return Ok(());
        }
    };
    let servers = doc.entry("mcp_servers").or_insert(toml_edit::table());
    if let Some(t) = servers.as_table_mut() {
        t.set_implicit(true);
        let mut zell = toml_edit::Table::new();
        zell.insert("command", toml_edit::value("zell-mcp"));
        zell.insert("args", toml_edit::value(toml_edit::Array::new()));
        t.insert("zell", toml_edit::Item::Table(zell));
    }
    put(report, path, old.as_deref(), &doc.to_string())
}

fn mcp_server() -> serde_json::Value {
    serde_json::json!({ "command": "zell-mcp", "args": [] })
}

/// Writes the configuration of `agents` into the project at `dir`.
pub fn write(dir: &Path, agents: &[Agent]) -> Result<Report, String> {
    let mut r = Report::default();
    let mut agents_md = false;
    for a in agents {
        match a {
            Agent::Claude => {
                let source = serde_json::json!({ "source": { "source": "github", "repo": MARKETPLACE_REPO } });
                json_entry(&mut r, dir.join(".claude/settings.json"), &["extraKnownMarketplaces", "zell"], source)?;
                json_entry(&mut r, dir.join(".claude/settings.json"), &["enabledPlugins", "zell@zell"], serde_json::json!(true))?;
                r.notes.push(format!("claude: teammates are offered the zell plugin on trust; or run `claude plugin marketplace add {MARKETPLACE_REPO}` and `claude plugin install zell@zell`"));
            }
            Agent::ClaudeSkills => {
                owned_file(&mut r, dir.join(".claude/skills/zell/SKILL.md"), ZELL_SKILL)?;
                owned_file(&mut r, dir.join(".claude/skills/zell-packages/SKILL.md"), PACKAGES_SKILL)?;
                json_entry(&mut r, dir.join(".mcp.json"), &["mcpServers", "zell"], mcp_server())?;
            }
            Agent::Codex => {
                agents_md = true;
                codex_toml(&mut r, dir.join(".codex/config.toml"))?;
                r.notes.push("codex: .codex/config.toml is read for trusted projects; or run `codex mcp add zell -- zell-mcp`".into());
            }
            Agent::Gemini => {
                markdown_section(&mut r, dir.join("GEMINI.md"))?;
                json_entry(&mut r, dir.join(".gemini/settings.json"), &["mcpServers", "zell"], mcp_server())?;
            }
            Agent::Cursor => {
                owned_file(&mut r, dir.join(".cursor/rules/zell.mdc"), &cursor_rule())?;
                json_entry(&mut r, dir.join(".cursor/mcp.json"), &["mcpServers", "zell"], mcp_server())?;
            }
            Agent::Windsurf => {
                owned_file(&mut r, dir.join(".windsurf/rules/zell.md"), &windsurf_rule())?;
                r.notes.push("windsurf: MCP servers are user-level; add {\"mcpServers\": {\"zell\": {\"command\": \"zell-mcp\", \"args\": []}}} to ~/.codeium/windsurf/mcp_config.json".into());
            }
            Agent::Cline => {
                owned_file(&mut r, dir.join(".clinerules/zell.md"), &guide_file())?;
                r.notes.push("cline: MCP servers are user-level; add \"zell\": {\"command\": \"zell-mcp\", \"args\": []} under mcpServers in cline_mcp_settings.json (MCP Servers > Configure)".into());
            }
            Agent::Aider => {
                markdown_section(&mut r, dir.join("CONVENTIONS.md"))?;
                let conf = dir.join(".aider.conf.yml");
                match std::fs::read_to_string(&conf) {
                    Err(_) => put(&mut r, conf, None, "# Zell conventions for aider (zell init --agents aider)\nread: CONVENTIONS.md\ntest-cmd: zell test\n")?,
                    Ok(t) if t.contains("CONVENTIONS.md") => r.files.push((conf, Outcome::Unchanged)),
                    Ok(_) => r.files.push((conf, Outcome::Skipped("add CONVENTIONS.md to its `read:` list".into()))),
                }
            }
            Agent::Zed => {
                agents_md = true;
                json_entry(&mut r, dir.join(".zed/settings.json"), &["context_servers", "zell"], mcp_server())?;
            }
            Agent::Copilot => {
                agents_md = true;
                json_entry(&mut r, dir.join(".vscode/mcp.json"), &["servers", "zell"], serde_json::json!({ "type": "stdio", "command": "zell-mcp", "args": [] }))?;
            }
        }
    }
    if agents_md {
        markdown_section(&mut r, dir.join("AGENTS.md"))?;
    }
    // one entry per file (written twice: created, then updated = created)
    let mut files: Vec<(PathBuf, Outcome)> = Vec::new();
    for (p, o) in r.files {
        match files.iter_mut().find(|(q, _)| *q == p) {
            Some((_, prev)) if *prev == Outcome::Created => {}
            Some((_, prev)) if o != Outcome::Unchanged => *prev = o,
            Some(_) => {}
            None => files.push((p, o)),
        }
    }
    r.files = files;
    Ok(r)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tmp(name: &str) -> PathBuf {
        let d = std::env::temp_dir().join(format!("zell-agents-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        std::fs::create_dir_all(&d).unwrap();
        d
    }

    /// The static copies in `agents/` (for agents set up by hand) are
    /// what `zell init --agents` writes; `ZELL_BLESS=1` rewrites them.
    #[test]
    fn agent_templates_are_in_sync() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../agents");
        for (rel, want) in [("templates/AGENTS.md", guide_file()), ("gemini/GEMINI.md", guide_file())] {
            let path = root.join(rel);
            if std::env::var_os("ZELL_BLESS").is_some() {
                std::fs::write(&path, &want).unwrap();
            }
            let got = std::fs::read_to_string(&path).unwrap_or_default();
            assert!(got == want, "agents/{rel} is stale: run ZELL_BLESS=1 cargo test -p zell --lib agent_templates");
        }
    }

    #[test]
    fn parses_agent_lists() {
        assert_eq!(parse_list("claude, codex,claude").unwrap(), vec![Agent::Claude, Agent::Codex]);
        assert_eq!(parse_list("all").unwrap().len(), Agent::ALL.len());
        assert_eq!(parse_list("claude-code,vscode").unwrap(), vec![Agent::Claude, Agent::Copilot]);
        assert!(parse_list("emacs").unwrap_err().contains("unknown agent `emacs`"));
        assert!(parse_list("").is_err());
    }

    #[test]
    fn the_guide_is_both_skills_without_frontmatter() {
        let g = guide_section();
        assert!(g.starts_with(BEGIN) && g.ends_with(&format!("{END}\n")));
        assert!(!g.contains("description:"), "frontmatter dropped");
        assert!(g.contains("\n## Zell for coding agents\n") && g.contains("\n### Errors: `T!`, `?`, `try`\n"));
        assert!(g.contains("\n## Zell packages and projects\n"));
        // code fences keep their `#` lines (TOML comments) as they are
        assert!(g.contains("\n[package]\n"));
        assert!(cursor_rule().starts_with("---\ndescription: ") && windsurf_rule().contains("trigger: glob"));
    }

    #[test]
    fn writes_and_merges_agent_files() {
        let d = tmp("write");
        std::fs::write(d.join("AGENTS.md"), "# My project\n\nBuild with make.\n").unwrap();
        std::fs::create_dir_all(d.join(".cursor")).unwrap();
        std::fs::write(d.join(".cursor/mcp.json"), "{\"mcpServers\": {\"other\": {\"command\": \"x\"}}}").unwrap();
        std::fs::create_dir_all(d.join(".zed")).unwrap();
        std::fs::write(d.join(".zed/settings.json"), "// comments\n{}").unwrap();
        let r = write(&d, &parse_list("all,claude-skills").unwrap()).unwrap();
        let agents = std::fs::read_to_string(d.join("AGENTS.md")).unwrap();
        assert!(agents.starts_with("# My project\n\nBuild with make.\n\n<!-- zell:begin"), "{agents}");
        assert_eq!(agents.matches(BEGIN).count(), 1);
        let cursor: serde_json::Value = serde_json::from_str(&std::fs::read_to_string(d.join(".cursor/mcp.json")).unwrap()).unwrap();
        assert_eq!(cursor["mcpServers"]["other"]["command"], "x");
        assert_eq!(cursor["mcpServers"]["zell"]["command"], "zell-mcp");
        let claude: serde_json::Value = serde_json::from_str(&std::fs::read_to_string(d.join(".claude/settings.json")).unwrap()).unwrap();
        assert_eq!(claude["enabledPlugins"]["zell@zell"], true);
        assert_eq!(claude["extraKnownMarketplaces"]["zell"]["source"]["repo"], MARKETPLACE_REPO);
        let codex = std::fs::read_to_string(d.join(".codex/config.toml")).unwrap();
        assert!(codex.contains("[mcp_servers.zell]\ncommand = \"zell-mcp\""), "{codex}");
        assert!(std::fs::read_to_string(d.join(".claude/skills/zell/SKILL.md")).unwrap().starts_with("---\nname: zell\n"));
        for f in ["GEMINI.md", ".gemini/settings.json", ".cursor/rules/zell.mdc", ".windsurf/rules/zell.md", ".clinerules/zell.md", "CONVENTIONS.md", ".aider.conf.yml", ".vscode/mcp.json", ".mcp.json"] {
            assert!(d.join(f).is_file(), "{f}");
        }
        let zed = r.files.iter().find(|(p, _)| p.ends_with(".zed/settings.json")).unwrap();
        assert!(matches!(&zed.1, Outcome::Skipped(n) if n.contains("context_servers")), "{zed:?}");
        // A second run changes nothing; an edited section is replaced.
        let again = write(&d, &parse_list("all,claude-skills").unwrap()).unwrap();
        assert!(again.files.iter().all(|(_, o)| matches!(o, Outcome::Unchanged | Outcome::Skipped(_))), "{:?}", again.files);
        std::fs::write(d.join("AGENTS.md"), agents.replace("## Zell for coding agents", "## stale") + "\nTail.\n").unwrap();
        write(&d, &[Agent::Codex]).unwrap();
        let fixed = std::fs::read_to_string(d.join("AGENTS.md")).unwrap();
        assert!(fixed.contains("## Zell for coding agents") && !fixed.contains("## stale") && fixed.ends_with("\nTail.\n"), "{fixed}");
        let _ = std::fs::remove_dir_all(&d);
    }
}
