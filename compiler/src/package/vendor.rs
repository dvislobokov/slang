//! `zell vendor`: copies every module of the graph into
//! `vendor/<module path>@<version>/` and writes `vendor/modules.yaml`.
//! While `vendor/modules.yaml` exists, builds read modules from there
//! (checked against `zell.lock`) and never touch the network or the store.

use super::graph::Project;
use super::store;
use serde::{Deserialize, Serialize};
use std::path::Path;

/// The list of vendored modules.
pub const MODULES_FILE: &str = "modules.yaml";

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct VendoredModule {
    pub h1: String,
    pub module: String,
    pub version: String,
}

fn copy_tree(from: &Path, to: &Path) -> Result<usize, String> {
    let mut n = 0;
    std::fs::create_dir_all(to).map_err(|e| format!("cannot create {}: {e}", to.display()))?;
    for e in std::fs::read_dir(from).map_err(|e| format!("cannot read {}: {e}", from.display()))? {
        let e = e.map_err(|e| e.to_string())?;
        let name = e.file_name();
        if name == store::MARKER {
            continue;
        }
        let p = e.path();
        if p.is_dir() {
            n += copy_tree(&p, &to.join(&name))?;
        } else {
            let dest = to.join(&name);
            std::fs::copy(&p, &dest).map_err(|e| format!("cannot copy {}: {e}", p.display()))?;
            // Store files are read-only; vendored copies are ordinary files.
            if let Ok(m) = std::fs::metadata(&dest) {
                let mut perm = m.permissions();
                #[allow(clippy::permissions_set_readonly_false)]
                perm.set_readonly(false);
                let _ = std::fs::set_permissions(&dest, perm);
            }
            n += 1;
        }
    }
    Ok(n)
}

/// Writes `vendor/` for `project` (whose modules are materialised).
/// Returns the vendored modules.
pub fn vendor(project: &Project) -> Result<Vec<VendoredModule>, String> {
    let dir = project.root.join("vendor");
    let mut list = Vec::new();
    for p in &project.packages {
        if let super::graph::Source::Module { path, version, h1, .. } = &p.source {
            let dest = dir.join(format!("{}@{version}", store::escape_path(path)));
            copy_tree(&p.dir, &dest)?;
            list.push(VendoredModule { h1: h1.clone(), module: path.clone(), version: version.clone() });
        }
    }
    list.sort_by(|a, b| a.module.cmp(&b.module));
    let text = format!("# vendor/modules.yaml: generated by `zell vendor`; delete vendor/ to use .zell/deps again.\n{}", serde_yaml::to_string(&list).map_err(|e| e.to_string())?);
    std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    std::fs::write(dir.join(MODULES_FILE), text).map_err(|e| format!("cannot write vendor/{MODULES_FILE}: {e}"))?;
    Ok(list)
}
