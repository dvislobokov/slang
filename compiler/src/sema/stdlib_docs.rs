/// The documentation of a constant or builtin struct (member), if listed.
pub fn const_doc(path: &str) -> Option<&'static str> {
    CONST_DOCS.iter().find(|(p, _)| match p.strip_suffix('*') {
        Some(pre) => path.starts_with(pre) && !path[pre.len()..].contains('.'),
        None => *p == path,
    }).map(|(_, d)| *d)
}

